def shape(x, y, w, h, color, radius=False):
    sh = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE if radius else MSO_SHAPE.RECTANGLE, Inches(x/120), Inches(y/120), Inches(w/120), Inches(h/120))
    sh.fill.solid(); sh.fill.fore_color.rgb = RGBColor.from_string(color); sh.line.fill.background()
    if radius:
        sh.adjustments[0] = .12
    current.append(f'<div style="position:absolute;left:{x}px;top:{y}px;width:{w}px;height:{h}px;background:#{color};border-radius:{22 if radius else 0}px"></div>')

def text(value, x, y, w, h, size=32, color=INK, bold=False, align='right'):
    box = slide.shapes.add_textbox(Inches(x/120), Inches(y/120), Inches(w/120), Inches(h/120))
    tf = box.text_frame; tf.clear(); tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    for i, line in enumerate(value.split('\n')):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = {'right': PP_ALIGN.RIGHT, 'left': PP_ALIGN.LEFT, 'center': PP_ALIGN.CENTER}[align]
        p.line_spacing = 1.18; p.space_after = Pt(5)
        p._p.get_or_add_pPr().set('rtl', '1')
        r = p.add_run(); r.text = line; r.font.name = 'Arial'; r.font.size = Pt(size*.6)
        r.font.bold = bold; r.font.color.rgb = RGBColor.from_string(color)
        r._r.get_or_add_rPr().set('lang', 'he-IL')
    current.append(f'<div dir="rtl" style="position:absolute;left:{x}px;top:{y}px;width:{w}px;height:{h}px;font-size:{size}px;color:#{color};font-weight:{700 if bold else 400};text-align:{align};line-height:1.18;white-space:pre-line">{html.escape(value)}</div>')

def picture(name, x, y, w, h):
    path = ASSETS/f'{name}.png'
    slide.shapes.add_picture(str(path), Inches(x/120), Inches(y/120), width=Inches(w/120), height=Inches(h/120))
    encoded = base64.b64encode(path.read_bytes()).decode()
    current.append(f'<img src="data:image/png;base64,{encoded}" style="position:absolute;left:{x}px;top:{y}px;width:{w}px;height:{h}px;border-radius:18px"/>')

